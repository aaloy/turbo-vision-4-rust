//! Hand-drawn 8x16 glyphs for the PNG renderer: CP437's symbols, Greek and
//! maths, the Latin-1 letters and signs, and the marks the framework draws.
//!
//! The bitmaps are drawn in the style of the embedded Spleen font: capitals
//! on rows 2-11, the x-height on rows 5-11, descenders down to row 14, and
//! two-pixel vertical strokes. Accented letters are not drawn by hand: they
//! are the font's own letter plus a mark (see [`composed`]).
//!
//! Each [`Sheet`] lays several glyphs side by side, one string per pixel row,
//! eight columns per glyph (`#` = ink) and a space between glyphs, so the
//! table reads as the glyphs themselves.

