/// The scan-lines of a mark that sits above a letter.
fn mark_rows(mark: Mark) -> &'static [u8] {
    match mark {
        Mark::Grave => &[0b0011_0000, 0b0001_1000],
        Mark::Acute => &[0b0000_1100, 0b0001_1000],
        Mark::Circumflex => &[0b0011_1100, 0b0110_0110],
        Mark::Tilde => &[0b0111_0110, 0b1101_1100],
        Mark::Diaeresis => &[0b0110_0110, 0b0110_0110],
        Mark::Ring => &[0b0011_1100, 0b0110_0110, 0b0011_1100],
        Mark::Cedilla | Mark::Stroke | Mark::Bar => &[],
    }
}

/// First row of a capital in the embedded font, and of a lowercase x-height.
const CAP_TOP: usize = 2;
const X_TOP: usize = 5;
/// Last row of a letter without a descender.
const BASELINE: usize = 11;

/// Build a composed Latin-1 letter: the font's letter plus its mark.
fn composed(ch: char) -> Option<GlyphMask> {
    let &(_, base, mark) = COMPOSED.iter().find(|(c, _, _)| *c == ch)?;
    let mut mask = font_glyph(base as u32);
    match mark {
        Mark::Cedilla => {
            // Below the baseline, hanging from the bottom of the C.
            mask[12] |= 0b0001_1000;
            mask[13] |= 0b0000_1100;
            mask[14] |= 0b0011_1000;
        }
        Mark::Bar => mask[6] |= 0b1111_0000,
        Mark::Stroke => {
            // A slash from the bottom-left to the top-right of the letter,
            // inside its own rows.
            let top = if base.is_ascii_uppercase() {
                CAP_TOP
            } else {
                X_TOP
            };
            let bottom = BASELINE;
            for (y, row) in mask.iter_mut().enumerate().take(bottom + 1).skip(top) {
                let x = (bottom - y) * (FONT_W - 1) / (bottom - top);
                *row |= 0x80 >> x;
            }
        }
        _ => {
            let rows = mark_rows(mark);
            let top = if base.is_ascii_uppercase() {
                // Lower the capital by a row to make room for the mark.
                lower_capital(&mut mask);
                0
            } else {
                if base == 'i' {
                    // A dotless i under the mark.
                    mask[..X_TOP].fill(0);
                }
                X_TOP - 1 - rows.len()
            };
            for (row, bits) in mask[top..].iter_mut().zip(rows) {
                *row |= bits;
            }
        }
    }
    Some(mask)
}

/// Shift the top of a capital down one row, dropping the first scan-line
/// that repeats the one above it, so the letter keeps its shape and baseline
/// and row [`CAP_TOP`] comes free. Returns whether a row could be dropped.
fn lower_capital(mask: &mut GlyphMask) -> bool {
    let Some(dup) = (CAP_TOP + 1..11).find(|&y| mask[y] != 0 && mask[y] == mask[y - 1]) else {
        return false;
    };
    mask.copy_within(CAP_TOP..dup, CAP_TOP + 1);
    mask[CAP_TOP] = 0;
    true
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sheets_are_well_formed() {
        for sheet in SHEETS {
            let n = sheet.chars.chars().count();
            for row in sheet.rows {
                assert_eq!(row.len(), n * (FONT_W + 1) - 1, "{}: {row}", sheet.chars);
                assert!(row.bytes().all(|b| b"#. ".contains(&b)), "{}", sheet.chars);
            }
        }
    }

    #[test]
    fn no_character_is_drawn_twice() {
        let mut seen = std::collections::HashSet::new();
        let all = SHEETS
            .iter()
            .flat_map(|s| s.chars.chars())
            .chain(COMPOSED.iter().map(|&(c, _, _)| c));
        for c in all {
            assert!(seen.insert(c), "{c} is defined twice");
        }
    }

    #[test]
    fn every_accented_capital_keeps_its_shape() {
        for &(ch, base, _) in COMPOSED {
            if base.is_ascii_uppercase() {
                let mut mask = font_glyph(base as u32);
                assert!(lower_capital(&mut mask), "{ch}: no row of {base} to drop");
            }
        }
    }

    #[test]
    fn strokes_stay_inside_their_letter() {
        // The slash of Ø and ø adds no ink above or below the O's own rows.
        for &(ch, base, mark) in COMPOSED {
            if mark == Mark::Stroke {
                let letter = font_glyph(base as u32);
                let inked =
                    |m: &GlyphMask| -> Vec<usize> { (0..FONT_H).filter(|&y| m[y] != 0).collect() };
                let rows = inked(&letter);
                let (first, last) = (rows[0], rows[rows.len() - 1]);
                for y in inked(&composed(ch).unwrap()) {
                    assert!((first..=last).contains(&y), "{ch}: ink on row {y}");
                }
            }
        }
    }

    #[test]
    fn marks_sit_clear_of_lowercase_letters() {
        // A blank row between the mark and the x-height.
        for &(ch, base, mark) in COMPOSED {
            if base.is_ascii_lowercase() && !matches!(mark, Mark::Cedilla | Mark::Stroke) {
                let m = composed(ch).unwrap();
                assert_eq!(m[X_TOP - 1], 0, "{ch}");
                assert_ne!(m[X_TOP - 2], 0, "{ch}");
            }
        }
    }
}
