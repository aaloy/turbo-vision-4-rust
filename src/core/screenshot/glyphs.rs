/// The hand-drawn or composed glyph for `ch`, if there is one.
pub(super) fn glyph(ch: char) -> Option<GlyphMask> {
    match ch {
        // Soft hyphen: shown where it is, as a hyphen.
        '\u{AD}' => Some(font_glyph('-' as u32)),
        // Inverse bullet and inverse circle.
        '◘' => sheet_glyph('•').map(inverse),
        '◙' => sheet_glyph('○').map(inverse),
        _ => sheet_glyph(ch).or_else(|| composed(ch)),
    }
}

/// Look `ch` up in [`SHEETS`].
fn sheet_glyph(ch: char) -> Option<GlyphMask> {
    SHEETS.iter().find_map(|sheet| {
        let index = sheet.chars.chars().position(|c| c == ch)?;
        let start = index * (FONT_W + 1);
        let mut mask = [0u8; FONT_H];
        for (row, line) in mask.iter_mut().zip(sheet.rows) {
            let bits = line.as_bytes().get(start..start + FONT_W)?;
            *row = bits
                .iter()
                .fold(0, |acc, &b| (acc << 1) | u8::from(b == b'#'));
        }
        Some(mask)
    })
}

fn inverse(mask: GlyphMask) -> GlyphMask {
    mask.map(|row| !row)
}

